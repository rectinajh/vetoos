/**
 * Content addressing for the RULES THEMSELVES (docs/VERIFIABLE_RISK_ENGINE.md §4.3).
 *
 * Hashing the policy file is not enough: the engine source is also a rule.
 * Deleting a deny branch changes verdicts without touching any policy JSON.
 *
 * `RULESET_HASH` covers the decision-relevant sources:
 *     packages/risk/src/engine.ts
 *     packages/risk/src/policy.ts
 * (line endings normalised so the digest is platform-independent).
 *
 * It is verified by `ruleset.test.ts` on every `pnpm test`, which makes the
 * ruleset a *gate*: change a rule without re-stamping and CI fails. That is
 * deliberate — without it, "the rules changed" would be indistinguishable from
 * "the record was tampered with" during verification.
 *
 * Re-stamp after an intentional rule change:
 *     pnpm ruleset:stamp
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { hashOf } from "@vetoos/audit";

/** Semantic version of the risk engine. Bump on ANY change that can move a verdict. */
export const ENGINE_VERSION = "risk/1.1.0";

/** Files whose content defines the ruleset. */
export const RULESET_FILES = [
  "packages/risk/src/engine.ts",
  "packages/risk/src/policy.ts",
] as const;

/** Generated by `pnpm ruleset:stamp`; asserted by ruleset.test.ts. */
export const RULESET_HASH = "bab7abc7c4de289f8c2f1b58203d5e2f8b4c18dc0947730719dd92e7bd18d85d";

/** Normalise line endings so Windows and POSIX checkouts hash identically. */
export function normalizeSource(src: string): string {
  return src.replace(/\r\n/g, "\n");
}

/** Recompute the ruleset hash from source files on disk (repo-root relative). */
export function computeRulesetHash(read: (path: string) => string): string {
  const sources: Record<string, string> = {};
  for (const file of RULESET_FILES) sources[file] = normalizeSource(read(file));
  return hashOf(sources);
}

/** Convenience: read the real files, resolving repo-root-relative paths. */
export function computeRulesetHashFromDisk(repoRoot: string): string {
  return computeRulesetHash((p) => readFileSync(join(repoRoot, p), "utf8"));
}
